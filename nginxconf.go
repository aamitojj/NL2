package main

// Generates the nginx config for a site's production container from the same
// parsed rules the App Testing preview uses. See netlifyrules.go for the
// semantics. The file is mounted at /etc/nginx/conf.d/default.conf.

import (
	"fmt"
	"strings"
)

const defaultCacheControl = "public, max-age=0, must-revalidate"

// nginxEscape quotes a value for use inside "..." in nginx config. "$" is
// produced through the $hp_dollar variable because nginx has no escape for it.
func nginxEscape(s string) string {
	s = strings.ReplaceAll(s, `\`, `\\`)
	s = strings.ReplaceAll(s, `"`, `\"`)
	s = strings.ReplaceAll(s, `$`, `${hp_dollar}`)
	return s
}

// nginxTarget converts a rule target into an nginx string using the copied
// capture variables ($hpv_<name>).
func nginxTarget(to string, names map[string]bool) string {
	return targetTokenRe.ReplaceAllStringFunc(to, func(tok string) string {
		if names[tok[1:]] {
			return "${hpv_" + tok[1:] + "}"
		}
		return tok
	})
}

func captureNames(r *RedirectRule) []string {
	var out []string
	for _, n := range r.re.SubexpNames() {
		if strings.HasPrefix(n, "hpc_") {
			out = append(out, n[4:])
		}
	}
	return out
}

func writeRuleBlock(b *strings.Builder, r *RedirectRule, idx int, matchVar string, indent string) {
	names := map[string]bool{}
	caps := captureNames(r)
	for _, n := range caps {
		names[n] = true
	}
	fmt.Fprintf(b, "%s# %s line %d: %s %s %d%s\n", indent, r.Source, r.Line, r.From, r.To, r.Status, map[bool]string{true: "!", false: ""}[r.Force])
	fmt.Fprintf(b, "%sif (%s ~ \"%s\") {\n", indent, matchVar, r.reSrc)
	in := indent + "    "
	for _, n := range caps {
		fmt.Fprintf(b, "%sset $hpv_%s $hpc_%s;\n", in, n, n)
	}
	target := nginxTarget(r.To, names)
	switch r.Status {
	case 200:
		fmt.Fprintf(b, "%sset $hp_rw 1;\n", in)
		fmt.Fprintf(b, "%srewrite ^ \"%s\" last;\n", in, target)
	case 404, 410:
		fmt.Fprintf(b, "%sset $hp_rw 1;\n", in)
		fmt.Fprintf(b, "%srewrite ^ /.hp-status/%d last;\n", in, idx)
	default:
		if strings.Contains(r.To, "?") {
			fmt.Fprintf(b, "%sreturn %d \"%s\";\n", in, r.Status, target)
		} else {
			fmt.Fprintf(b, "%sreturn %d \"%s$is_args$args\";\n", in, r.Status, target)
		}
	}
	fmt.Fprintf(b, "%s}\n", indent)
}

// generateNginxConf returns the server config. fs tells whether 404.html exists.
func generateNginxConf(rules *SiteRules, fs FileSet) string {
	if rules == nil {
		rules = &SiteRules{}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by HostPanel %s from _redirects, _headers and netlify.toml.\n# Do not edit on the server: it is replaced on every deployment.\n\n", Version)
	b.WriteString("geo $hp_dollar { default \"$\"; }\n")
	b.WriteString("\n")

	// Headers: one map per header name over the original request URI.
	// Later rules win, so entries are listed in reverse rule order (nginx
	// uses the first matching regex).
	type entry struct{ re, val string }
	perName := map[string][]entry{}
	display := map[string]string{}
	var order []string
	for _, h := range rules.Headers {
		local := map[string][]string{}
		var names []string
		for _, kv := range h.Values {
			k := strings.ToLower(kv[0])
			if _, ok := local[k]; !ok {
				names = append(names, k)
			}
			local[k] = append(local[k], kv[1])
			if _, ok := display[k]; !ok {
				display[k] = kv[0]
				order = append(order, k)
			}
		}
		re := strings.TrimSuffix(h.reSrc, "$") + `(?:\?.*)?$`
		for _, k := range names {
			perName[k] = append(perName[k], entry{re, strings.Join(local[k], ", ")})
		}
	}
	if _, ok := display["cache-control"]; !ok {
		display["cache-control"] = "Cache-Control"
		order = append(order, "cache-control")
	}
	varOf := map[string]string{}
	for i, k := range order {
		v := fmt.Sprintf("$hp_h%d", i)
		varOf[k] = v
		def := ""
		if k == "cache-control" {
			def = defaultCacheControl
		}
		fmt.Fprintf(&b, "# %s\nmap $request_uri %s {\n    default \"%s\";\n", display[k], v, def)
		es := perName[k]
		for j := len(es) - 1; j >= 0; j-- {
			fmt.Fprintf(&b, "    \"~%s\" \"%s\";\n", es[j].re, nginxEscape(es[j].val))
		}
		b.WriteString("}\n")
	}

	b.WriteString(`
server {
    listen 80 default_server;
    server_name _;
    root /usr/share/nginx/html;
    index index.html;
    absolute_redirect off;
    server_tokens off;
    gzip on;
    gzip_min_length 1024;
    gzip_types text/plain text/css application/javascript application/json application/xml image/svg+xml;
    # $hp_rw marks requests already rewritten by a rule; it must survive
    # internal redirects, so it is never initialised at server level.
    uninitialized_variable_warn off;
`)
	if fileOf(fs, "404.html") {
		b.WriteString("    error_page 404 /404.html;\n")
	}
	for _, k := range order {
		fmt.Fprintf(&b, "    add_header %s %s always;\n", display[k], varOf[k])
	}
	b.WriteString(`
    # Rule and config files are never published.
    location ~ "^/(_redirects|_headers|netlify\.toml)$" {
        set $hp_rw 1;
        return 404;
    }
`)
	// Status (404/410) rules get an internal location each.
	for i, r := range rules.Redirects {
		if r.Status == 404 || r.Status == 410 {
			tp, _, _ := strings.Cut(r.To, "?")
			fmt.Fprintf(&b, "    location = /.hp-status/%d {\n        internal;\n        error_page %d \"%s\";\n        return %d;\n    }\n", i, r.Status, tp, r.Status)
		}
	}
	forced := func(loc, tryFiles string) {
		fmt.Fprintf(&b, "\n    location %s {\n        set $hp_m \"$hp_rw$uri\";\n", loc)
		for i, r := range rules.Redirects {
			if r.Force {
				writeRuleBlock(&b, r, i, "$hp_m", "        ")
			}
		}
		fmt.Fprintf(&b, "        %s\n    }\n", tryFiles)
	}
	// Existing files win (clean URLs: /about -> about.html). Paths ending in
	// "/" never match a file directly; folders are handled in @hp_rules.
	// (Two locations instead of an "if": an if block would replace the
	// location and drop try_files.)
	forced("/", "try_files $uri $uri.html @hp_rules;")
	forced(`~ "/$"`, "try_files /.hp-none @hp_rules;")
	b.WriteString(`
    location @hp_rules {
        # Folders: /docs -> 301 /docs/, /docs/ -> docs/index.html
        set $hp_d "";
        if (-f $request_filename/index.html) {
            set $hp_d "D";
        }
        if ($uri ~ "/$") {
            set $hp_d "${hp_d}S";
        }
        if ($hp_d = "D") {
            return 301 "$uri/$is_args$args";
        }
        if ($hp_d = "DS") {
            set $hp_rw 1;
            rewrite ^ "${uri}index.html" last;
        }
        # /page/ -> 301 /page when page.html exists
        set $hp_t "/.hp-none";
        if ($uri ~ "^(?<hp_ns>/.+)/$") {
            set $hp_t $hp_ns;
        }
        if (-f $document_root$hp_t.html) {
            return 301 "$hp_t$is_args$args";
        }
        # A rewrite target that doesn't exist is a plain 404.
        if ($hp_rw) {
            return 404;
        }
`)
	for i, r := range rules.Redirects {
		if !r.Force {
			writeRuleBlock(&b, r, i, "$uri", "        ")
		}
	}
	b.WriteString(`        set $hp_rw 1;
        return 404;
    }
}
`)
	return b.String()
}
